/**
 * C99 code generator
 */

import * as fs from "fs"
import { normalizeTypes } from "../utils"
import { TypeDefinition } from "../"
import { Kind, StructStrict, EnumStrict, UnionStrict } from "../types"
import { DepGraph } from "dependency-graph"

export type Options = {
  typePrefix?: string
  noIncludes?: boolean
  /**
   * @internal
   * @private
   * @hidden
   */
  getEnumCode?: (def: EnumStrict) => string
}

export const defaultOptions: Options = {}

const addIndent = (line: string) => "    " + line

const C99TypeMap = {
  u8: "uint8_t",
  u16: "uint16_t",
  u32: "uint32_t",
  u64: "uint64_t",
  i8: "int8_t",
  i16: "int16_t",
  i32: "int32_t",
  i64: "int64_t",
  f64: "double",
}

/**
 * @internal
 * @private
 * @hidden
 */
export const getC99Type = (inName: string): string => {
  return inName in C99TypeMap ? C99TypeMap[inName] : inName
}

const getStructCode = (typeDef: StructStrict) => {
  const fields = typeDef.fields
    .map(field => {
      const c99Type = getC99Type(field.type)
      const name = field.length ? `${field.name}[${field.length}]` : field.name
      return `${c99Type} ${name};`
    })
    .map(addIndent)
    .join("\n")

  let result = ""
  result += "typedef struct {\n"
  result += fields + "\n"
  result += `} ${typeDef.name};\n`
  return result
}

const getEnumCode = (typeDef: EnumStrict) => {
  const variants = typeDef.variants
    .map(
      ([key, value]) =>
        `#define ${typeDef.name.toUpperCase()}_${key.toUpperCase()} = ${value};`,
    )
    .join("\n")

  return variants + "\n"
}

const getUnionCode = (typeDef: UnionStrict) => {
  const variants = typeDef.members
    .map(member => `${member} ${member};`)
    .map(addIndent)
    .join("\n")

  let result = ""
  result += "typedef union {\n"
  result += variants + "\n"
  result += `} ${typeDef.name};\n`
  return result
}

type C99TypeDefinition = {
  name: string
  content: string
  dependencies: string[]
}

const buildDepGraph = (
  definitions: C99TypeDefinition[],
): [DepGraph<any>, string[]] => {
  let missingTypes: Set<string> = new Set()

  let depGraph = new DepGraph()

  Object.keys(C99TypeMap).forEach(name => depGraph.addNode(name))

  definitions.forEach(def => depGraph.addNode(def.name))
  definitions.forEach(def => {
    def.dependencies.forEach(dep => {
      if (depGraph.hasNode(dep)) {
        depGraph.addDependency(def.name, dep)
      } else {
        missingTypes.add(dep)
      }
    })
  })

  return [depGraph, Array.from(missingTypes)]
}

/**
 * @internal
 * @private
 * @hidden
 */
export const prepareTypes = (typesDuck: TypeDefinition[], options: Options) => {
  const types = normalizeTypes(typesDuck)

  if (options.typePrefix) {
    types.forEach(typeDef => {
      typeDef.name = options.typePrefix + typeDef.name
    })
  }

  return types
}

/**
 * Generate C99 interfaces from Bendec types definitions
 */
export const generateString = (
  typesDuck: TypeDefinition[],
  options: Options,
) => {
  const types = prepareTypes(typesDuck, options)

  const definitions = types.map((typeDef): C99TypeDefinition => {
    const typeName = getC99Type(typeDef.name)

    switch (typeDef.kind) {
      case Kind.Primitive: {
        return {
          name: typeName,
          content: `// primitive built-in: ${typeName}`,
          dependencies: [],
        }
      }
      case Kind.Alias: {
        const typeAlias = getC99Type(typeDef.alias)
        return {
          name: typeName,
          content: `typedef ${typeAlias} ${typeName};`,
          dependencies: [typeAlias],
        }
      }
      case Kind.Struct: {
        const dependencies = typeDef.fields.map(field => field.type)
        return { name: typeName, content: getStructCode(typeDef), dependencies }
      }
      case Kind.Enum: {
        const generate = options.getEnumCode || getEnumCode
        return {
          name: typeName,
          content: generate(typeDef),
          dependencies: [],
        }
      }
      case Kind.Union: {
        return {
          name: typeName,
          content: getUnionCode(typeDef),
          dependencies: typeDef.members,
        }
      }
      case Kind.Array: {
        const c99Type = getC99Type(typeDef.type)
        return {
          name: typeName,
          content: `typedef ${c99Type} ${typeName}[${typeDef.length}];`,
          dependencies: [typeDef.type],
        }
      }
    }
  })

  let [depGraph, missingTypes] = buildDepGraph(definitions)

  let result = "// Generated by BenDec Type Generator\n"

  result += "#pragma once\n"

  if (!options.noIncludes) {
    result += "#include <stdint.h>\n"
  }

  result += "#pragma pack(push)\n"
  result += "#pragma pack(1)\n"

  result += missingTypes.map(x => `// missing definition: ${x}`).join("\n")

  result += depGraph
    .overallOrder()
    .map(name => definitions.find(def => def.name == name))
    .filter(def => def != null)
    .map(def => def.content)
    .join("\n")

  result += "#pragma pack(pop)\n"

  return result
}

/**
 * Generate C99 types from Bendec types definitions
 */
export const generate = (types: any[], fileName: string, options?: Options) => {
  const moduleWrapped = generateString(types, options)

  fs.writeFileSync(fileName, moduleWrapped)
  console.log(`WRITTEN: ${fileName}`)
}
